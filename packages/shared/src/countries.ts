export const COUNTRIES: Country[] = ROWS.map(([code, name, aliases]) => ({ code, name, aliases }));

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** True for a well-formed, known alpha-2 code. Case-insensitive. */
export function isCountryCode(v: unknown): boolean {
  return typeof v === 'string' && BY_CODE.has(v.trim().toUpperCase());
}

/** The country's English name, or the code back if it isn't one we know. */
export function countryName(code: string | null | undefined): string {
  if (!code) return '';
  return BY_CODE.get(code.trim().toUpperCase())?.name ?? code;
}

