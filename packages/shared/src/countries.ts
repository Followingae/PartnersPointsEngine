/**
 * ISO 3166-1 alpha-2 countries.
 *
 * One list for the API, both consoles and the app. Nationality is stored as the
 * code and rendered as the name, so this is the only place a spelling lives.
 * `gender` set the opposite precedent — a free string whose valid values were
 * duplicated across three hardcoded UI lists — and at ~250 countries that would
 * have been considerably worse.
 *
 * Aliases exist because people search for the name they use rather than the one
 * a standards body prints: someone in Dubai types "UAE", and anyone with a
 * plain keyboard types "Turkiye" without the diacritic.
 */

export interface Country {
  code: string;
  name: string;
  /** Extra lower-case terms a search box should also match. */
  aliases?: string;
}

